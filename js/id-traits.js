/* 正規表現エスケープ */
function escapeRegex(s) {
  return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

/* ================================================================
   メイン判定関数
   ================================================================ */
function idaCalcTraits(posts, threadList, threadsMade, hourCounts, totalPosts) {
  if (!totalPosts || totalPosts === 0 || !posts || posts.length === 0) return [];

  // 時系列昇順ソート
  var sortedPosts = posts.slice().sort(function(a, b) {
    return new Date(a.posted_at).getTime() - new Date(b.posted_at).getTime();
  });

  var scores = {};

  /* ------ 全レスの集計 ------ */
  var mediaPostCount = 0;
  var totalAnchoredPosts = 0;
  var totalChars = 0;
  var shortCount = 0;   // 15文字以下
  var longCount = 0;    // 120文字以上
  var grassTotalCount = 0;
  var grassPostCount = 0;
  
  // レスバ用語（煽り・論争ワード）
  var replyBattleRegex = /(?:アホ|バカ|ガイジ|エアプ|にわか|知ったか|論破|反論|ソース出せ|ソースは|お前さぁ|必死だな|必死すぎ|キモい|低学歴|低脳|池沼|雑魚|ざこ|クソゴミ)/;
  var replyBattleHits = 0;

  sortedPosts.forEach(function(p) {
    var b = p.body || "";
    var cleanB = b.replace(/\r?\n|\s/g, "");
    var len = cleanB.length;
    totalChars += len;

    /* メディア検出（レス単位でカウント） */
    var hasMedia = MEDIA_PATTERNS.some(function(re) { return re.test(b); });
    if (hasMedia) mediaPostCount++;

    /* 安価付きレス */
    if (/>>\d+/.test(b)) totalAnchoredPosts++;

    /* 文字数判定 */
    if (len <= 15) shortCount++;
    if (len >= 120) longCount++;

    /* 草検出（レス単位・総出現数の両方を集計） */
    var grassHits = b.match(/草|[wWｗＷ]{2,}|(?:\s|^)[wWｗＷ]+(?=\s|$|>|」|）|\))/g);
    if (grassHits) {
      grassTotalCount += grassHits.length;
      grassPostCount++;
    }

    /* レスバ判定 */
    if (replyBattleRegex.test(b)) replyBattleHits++;
  });

  var avgChars = Math.round(totalChars / totalPosts);

  /* ------ コピペ検出 ------ */
  var bodyFreq = {};
  sortedPosts.forEach(function(p) {
    var key = (p.body || "").trim();
    if (key.length >= 15) {
      bodyFreq[key] = (bodyFreq[key] || 0) + 1;
    }
  });
  var maxCopipeFreq = 0;
  Object.keys(bodyFreq).forEach(function(k) {
    if (bodyFreq[k] >= 3 && bodyFreq[k] > maxCopipeFreq) {
      maxCopipeFreq = bodyFreq[k];
    }
  });

  /* ------ カテゴリ別キーワードスコア（1レス荒稼ぎ防止付き） ------ */
  Object.keys(TRAIT_DICT).forEach(function(catId) {
    var cat = TRAIT_DICT[catId];
    var score = 0;
    var matchedPosts = 0;

    sortedPosts.forEach(function(p) {
      var b = p.body || "";
      var postScore = 0;
      cat.words.forEach(function(w) {
        var re = new RegExp(escapeRegex(w), "gi");
        var m = b.match(re);
        if (m) postScore += Math.min(m.length, 3); // 1レスあたり同単語は最大3カウント
      });
      if (postScore > 0) {
        score += postScore;
        matchedPosts++;
      }
    });

    /* スレタイからのボーナス */
    threadList.forEach(function(t) {
      var title = (t.title || "").toLowerCase();
      cat.words.forEach(function(w) {
        if (title.indexOf(w.toLowerCase()) !== -1) {
          score += cat.threadBonus;
        }
      });
    });

    /* スレ立て主ボーナス */
    threadsMade.forEach(function(tm) {
      var titleInfo = threadList.find(function(t) { return t.thread_id === tm.thread_id; });
      var title = titleInfo ? (titleInfo.title || "").toLowerCase() : "";
      cat.words.forEach(function(w) {
        if (title.indexOf(w.toLowerCase()) !== -1) score += cat.nusiBonus;
      });
    });

    // 最低マッチレス数以上に出現している場合のみスコア登録
    var minRequired = Math.min(cat.minPostCount || 3, Math.ceil(totalPosts * 0.1));
    if (matchedPosts >= minRequired && score > 0) {
      scores[catId] = score;
    }
  });

  /* ------ 行動系の属性判定 ------ */

  /* ニート: 1〜5時の投稿が8個以上 かつ 深夜割合が25%以上 */
  var nightCount = 0;
  for (var h = 1; h <= 5; h++) nightCount += hourCounts[h];
  if (nightCount >= 8 && (nightCount / totalPosts) >= 0.25) {
    scores.neet = nightCount;
  }

  /* 早起き: 初レスが5時台or6時台（深夜投稿が少なく、ニート判定なしの場合） */
  if (sortedPosts.length > 0 && !scores.neet) {
    var firstPostHour = new Date(sortedPosts[0].posted_at).getHours();
    var deepNightCount = (hourCounts[1] || 0) + (hourCounts[2] || 0) + (hourCounts[3] || 0);
    if ((firstPostHour === 5 || firstPostHour === 6) && deepNightCount <= 1) {
      scores.earlybird = firstPostHour === 5 ? 60 : 50;
    }
  }

  /* 24時間戦士: 18時間帯以上に書き込みがあり総レス30以上 */
  var activeHours = hourCounts.filter(function(c) { return c > 0; }).length;
  if (activeHours >= 18 && totalPosts >= 30) {
    scores.allday = activeHours;
  }

  /* ペタッw: メディア付きレスが5個以上 かつ レスの20%以上 */
  if (mediaPostCount >= 5 && (mediaPostCount / totalPosts) >= 0.20) {
    scores.peta = mediaPostCount;
  }

  /* スレ立て魔: スレ立て10件以上 */
  if (threadsMade.length >= 10) {
    scores.threadking = threadsMade.length * 10;
  }

  /* 長文民: 平均文字数60以上 or 長文率25%以上（最低5レス） */
  if (totalPosts >= 5 && (avgChars >= 60 || (longCount / totalPosts) >= 0.25)) {
    scores.chatty = avgChars;
  }

  /* 短文スナイパー: 10レス以上、平均文字数15以下 かつ 短文率70%以上 */
  if (totalPosts >= 10 && avgChars <= 15 && (shortCount / totalPosts) >= 0.70) {
    scores.sniper = Math.round((shortCount / totalPosts) * 100);
  }

  /* 連投マン: 20レス以上、平均投稿間隔が2分以内 */
  if (sortedPosts.length >= 20) {
    var firstT = new Date(sortedPosts[0].posted_at).getTime();
    var lastT = new Date(sortedPosts[sortedPosts.length - 1].posted_at).getTime();
    var avgMin = (lastT - firstT) / 60000 / (sortedPosts.length - 1);
    if (avgMin <= 2 && avgMin >= 0) {
      scores.machinegun = Math.round(100 - avgMin * 20);
    }
  }

  /* 安価職人: 安価付きレスが10件以上 かつ 安価率70%以上 */
  var anchorRate = totalAnchoredPosts / totalPosts;
  if (anchorRate >= 0.70 && totalAnchoredPosts >= 10) {
    scores.anchor = Math.round(anchorRate * 100);
  }

  /* 単発: 参加スレが1つだけ */
  if (threadList.length === 1) {
    scores.tanpatsu = 1;
  }

  /* 渡り鳥: 参加スレ25以上 */
  if (threadList.length >= 25) {
    scores.nomad = threadList.length;
  }

  /* コピペ職人: 同一内容（15文字以上）が3回以上 */
  if (maxCopipeFreq >= 3) {
    scores.copipe = maxCopipeFreq * 10;
  }

  /* 草生やし民: 草出現10回以上 かつ 草を含むレスが全体の20%以上（割合条件を適用） */
  if (grassTotalCount >= 10 && (grassPostCount / totalPosts) >= 0.20) {
    scores.grass = grassTotalCount;
  }

  /* レスバトラー: レスバ系ワード5回以上 かつ 全レスの15%以上 */
  if (replyBattleHits >= 5 && (replyBattleHits / totalPosts) >= 0.15) {
    scores.replymagnet = replyBattleHits;
  }

  /* ------ 結果配列の作成 ------ */
  var result = [];
  Object.keys(scores).forEach(function(id) {
    var def = TRAIT_DEFS[id];
    if (!def) return;
    if (scores[id] < def.minScore) return;
    result.push({
      id: id,
      icon: def.icon,
      name: def.name,
      score: scores[id],
      desc: def.desc
    });
  });

  /* スコア降順 */
  result.sort(function(a, b) { return b.score - a.score; });

  return result.slice(0, 8);
}
